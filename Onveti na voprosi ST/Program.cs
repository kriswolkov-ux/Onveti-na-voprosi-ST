// Вопрос 10 из 15
// Что делает Include() в EF Core?

// - Это жадная загрузка: EF добавляет JOIN и заполняет навигацию сразу, в этом
//   же запросе.

// - Без Include навигация останется null, а цикл по списку даст N+1 запрос.

// - ThenInclude идёт глубже по связи, AsSplitQuery —
//   когда коллекций несколько и JOIN раздувает ответ.

// - Для чтения часто выгоднее не Include, а проекция через Select в DTO.
// Пример:
//   var orders = await db.Orders
//       .Include(o => o.Customer)
//       .ToListAsync();


// Вопрос 12 из 15
// Чем Dapper отличается от EF Core?

// - Dapper — микро-ORM: SQL пишешь сам, он только подставляет параметры и
//   маппит строки в объекты.

// - Плюс: быстро, прозрачно, полный контроль над запросом. Минус: нет change
//   tracking, миграций и lazy loading.

// - EF Core — полноценная ORM: LINQ превращается в SQL, есть DbContext, трекер
//   изменений, миграции и связи.

// - Плюс: меньше ручного кода. Минус: SQL не всегда оптимален, легко поймать N+1.
// - Обычно EF берут на CRUD, а Dapper — на тяжёлые выборки и отчёты.

