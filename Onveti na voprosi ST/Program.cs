// Вопрос 2 из 15
// Почему нужно использовать SQL-параметры?

// - Значения уходят в базу отдельно от текста запроса, поэтому ввод не может
//   изменить сам запрос — это защита от SQL-инъекций.

// - Кавычки и апострофы не надо экранировать руками: «' OR 1=1 --» останется
//   обычной строкой.

// - Даты и decimal передаются в правильном типе и формате.
// - Текст запроса не меняется, поэтому SQL Server переиспользует готовый
//   план выполнения.

